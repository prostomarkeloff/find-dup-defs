/// The banners generators write at the top of what they write.
const GENERATED: &[&str] = &["@generated", "do not edit", "automatically generated", "autogenerated", "auto-generated", "generated by"];

/// Whether a file declares itself generated: a generator's banner in the comments before its first line
/// of code.
pub(crate) fn is_generated(src: &str) -> bool {
    let mut in_block = false;
    for line in src.lines().take(60) {
        let t = line.trim();
        let t = t.strip_prefix("<?php").map_or(t, str::trim);
        let comment = in_block || t.is_empty() || t.starts_with("//") || t.starts_with('#') || t.starts_with("/*") || t.starts_with('*');
        if !comment && !t.starts_with("declare(") && !t.starts_with("namespace ") {
            return false;
        }
        if t.contains("/*") && !t.contains("*/") {
            in_block = true;
        } else if t.contains("*/") {
            in_block = false;
        }
        let lower = t.to_ascii_lowercase();
        if comment && GENERATED.iter().any(|m| lower.contains(m)) {
            // "do not edit" is also the opening of the "Do not edit or add to this file if you wish
            // to upgrade … to newer versions" disclaimer that PrestaShop, Magento and kindred apps
            // stamp on every hand-maintained source file. That idiom names an upgrade and carries no
            // generation word, so it is not a generated-file banner — a real one says "generated" /
            // "@generated" (every other marker here contains "generat"). Without this the whole
            // PrestaShop/Magento tree reads as generated and yields nothing.
            let upgrade_disclaimer = lower.contains("do not edit") && lower.contains("upgrade") && !lower.contains("generat");
            if !upgrade_disclaimer {
                return true;
            }
        }
    }
    false
}

/// Whether a file is one no one edits as the project's code, whatever its contents:
///
/// * Composer's own runtime (`ClassLoader.php`, `InstalledVersions.php`), which `composer install`
///   copies verbatim into the vendor directory — however that directory is named: an application that
///   commits its dependencies per plugin carries one copy per plugin;
/// * a Drupal `*.api.php`, which documents the hooks a module invokes with example implementations and
///   is never loaded.
pub(crate) fn is_not_code(file: &str) -> bool {
    let path = std::path::Path::new(file);
    let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
    let parent = path.parent().and_then(|p| p.file_name()).and_then(|n| n.to_str()).unwrap_or("");
    name.ends_with(".api.php") || (parent == "composer" && matches!(name, "ClassLoader.php" | "InstalledVersions.php" | "platform_check.php"))
}

/// The declarations a namespace block holds at file scope, wherever a conditional or a bare block put
/// them.
fn top_items<'t>(items: &[Node<'t>]) -> Vec<Node<'t>> {
    fn walk<'t>(nodes: &[Node<'t>], out: &mut Vec<Node<'t>>) {
        for n in nodes {
            match n.kind() {
                "if_statement" => {
                    for body in crate::tree::fields(*n, "body") {
                        walk(&[body], out);
                    }
                    for alt in crate::tree::fields(*n, "alternative") {
                        for body in crate::tree::fields(alt, "body") {
                            walk(&[body], out);
                        }
                    }
                }
                "compound_statement" | "colon_block" | "declare_statement" => walk(&kids(*n), out),
                _ => out.push(*n),
            }
        }
    }
    let mut out = Vec::new();
    walk(items, &mut out);
    out
}

/// True when a body is a no-op, a stub or plumbing: empty; a single `return` of a variable, a literal or
/// a constant; a single `throw` of an exception built from literals; a deprecation notice, perhaps
/// followed by such a `return`; a getter (`return $this->x;`); or wiring — nothing but a call handing
/// its arguments on to the parent's method and properties set from parameters (`$this->x = $x;`), the
/// body of every setter and of a dependency-injected constructor, perhaps ending `return $this;`. None
/// of them is a refactor cluster — the last two are the boilerplate a PHP class is mostly made of, and
/// fifty `getId`s are fifty getters, not one duplication.
fn is_trivial(f: &Func) -> bool {
    let is_this = |e: &Expr| matches!(e, Expr::Var(v) if v == "this");
    let this_prop = |e: &Expr| matches!(e, Expr::Prop { e, name: Member::Name(_), .. } if is_this(e));
    let param = |e: &Expr| matches!(e, Expr::Var(v) if f.params.iter().any(|p| &p.name == v));
    let atoms = |args: &[crate::ir::Arg]| args.iter().all(|a| is_atom(&a.value) || matches!(&a.value, Expr::Spread(v) if is_atom(v)));
    let wiring = |s: &Stmt| match s {
        Stmt::Expr(Expr::StaticCall { scope, args, .. }) => matches!(scope.as_ref(), Expr::Name(n) if n == "parent") && atoms(args),
        Stmt::Assign { op, lhs, rhs } => op == "=" && this_prop(lhs) && (param(rhs) || is_atom(rhs)),
        _ => false,
    };
    // `_deprecated_function(__FUNCTION__, '4.3.0')`, `trigger_deprecation(…)`, `@trigger_error(…)`.
    let deprecation = |s: &Stmt| {
        let Stmt::Expr(e) = s else { return false };
        let call = if let Expr::Silence(inner) = e { inner.as_ref() } else { e };
        matches!(call, Expr::Call { f: callee, .. }
            if matches!(callee.as_ref(), Expr::Name(n) if n.to_ascii_lowercase().contains("deprecat") || n.eq_ignore_ascii_case("trigger_error")))
    };
    match f.body.as_slice() {
        [] | [Stmt::Return(None)] => true,
        [Stmt::Return(Some(e))] => is_atom(e) || this_prop(e),
        [Stmt::Throw(Expr::New { args, .. })] => atoms(args),
        [notice] if deprecation(notice) => true,
        [notice, Stmt::Return(value)] if deprecation(notice) => value.as_ref().is_none_or(is_atom),
        [body @ .., Stmt::Return(Some(back))] if is_this(back) && !body.is_empty() => body.iter().all(wiring),
        body => body.iter().all(wiring),
    }
}

fn is_atom(e: &Expr) -> bool {
    match e {
        Expr::Var(_) | Expr::Name(_) | Expr::Lit(..) | Expr::Bool(_) | Expr::Null | Expr::ClassConst { .. } => true,
        Expr::Array(elems) => elems.is_empty(),
        Expr::Unary { op, e } if op == "-" => is_atom(e),
        Expr::Paren(e) | Expr::Cast { e, .. } => is_atom(e),
        _ => false,
    }
}

/// Whether the runtime calls a method rather than the code: PHP's magic methods, which an operator, a
/// conversion or a missing member invokes.
fn magic(name: &str) -> bool {
    name.starts_with("__")
}

/// What a definition contributes beyond its location: its canonical forms and, for a callable, the
/// facets the perspective passes read.
struct DefCanon {
    cluster: Option<String>,
    analysis: Option<Analysis>,
    facets: Facets,
}

impl DefCanon {
    /// A body-bearing kind clustered by its canonical text alone (a class), or a raw-text kind (`None`).
    fn body(cluster: Option<String>) -> Self {
        Self { cluster, analysis: None, facets: Facets::default() }
    }
}

/// The class a method is read in: its name, the declaration, and the types its properties are declared
/// with — what a method reaches through `$this->prop`.
struct Owner<'c> {
    decl: &'c ClassDecl,
    props: HashMap<String, Type>,
}

impl<'c> Owner<'c> {
    fn new(decl: &'c ClassDecl) -> Self {
        let mut props = HashMap::new();
        for m in &decl.members {
            match m {
                ClassMember::Prop { name, ty: Some(ty), .. } => {
                    props.insert(name.clone(), ty.clone());
                }
                ClassMember::Method { name, sig, .. } if name.eq_ignore_ascii_case("__construct") => {
                    for p in sig.params.iter().filter(|p| p.promoted.is_some()) {
                        if let Some(ty) = &p.ty {
                            props.insert(p.name.clone(), ty.clone());
                        }
                    }
                }
                _ => {}
            }
        }
        Self { decl, props }
    }
}

/// One builder so every push site stays uniform.
struct Builder<'a> {
    source: &'a str,
    lines: &'a LineMap<'a>,
    file: &'a Arc<str>,
    /// Which lenses this run asked for; empty when it did not ask.
    lenses: Vec<Lens>,
    /// Names the file itself introduced — what every lens erases before it looks.
    file_names: HashSet<String>,
    /// The kinds and names already reported: a second definition of one is another configuration's.
    seen: HashSet<(&'static str, String)>,
    out: Vec<Def>,
}

impl Builder<'_> {
    /// Whether this is the file's first definition of `name` as `kind`.
    fn first(&mut self, kind: &'static KindSpec, name: &str) -> bool {
        self.seen.insert((kind.id, name.to_ascii_lowercase()))
    }

    /// One lens [`Def`] for this definition, when the run asked for lenses and the projection has enough
    /// to say. The record, the thinness floor and the scoring are the shared module's.
    fn push_lens(&mut self, name: &str, span: Node<'_>, facts: &LensFacts) {
        if self.lenses.is_empty() {
            return;
        }
        let start = span.start_byte();
        let (line, col) = self.lines.loc0(start);
        let loc = count_loc(self.source.get(start..span.end_byte()).unwrap_or(""));
        let site = DefSite { name, file: self.file, line, col, loc };
        if let Some(def) = lens_def("php", CanonDialect::Php, &site, &self.lenses, facts) {
            self.out.push(def);
        }
    }

    fn push(&mut self, kind: &'static KindSpec, name: String, span: Node<'_>, args: usize, canon: DefCanon) {
        let DefCanon { cluster: cluster_canonical, analysis, facets } = canon;
        let (start, end) = (span.start_byte(), span.end_byte());
        let (line, col) = self.lines.loc0(start);
        let text_orig = self.source.get(start..end).unwrap_or("").trim_end().to_owned();
        let loc = count_loc(&text_orig);
        self.out.push(Def {
            lang: "php",
            kind,
            name,
            file: Arc::clone(self.file),
            line,
            col,
            loc,
            args,
            text_orig,
            cluster_canonical,
            analysis,
            thickness: None,
            facets,
        });
    }

    /// A function or method: canonical forms, statement stream, what it reaches, and what it decides
    /// on. `owner` is the class a method is read in.
    #[allow(clippy::too_many_arguments)] // the parts of one callable, each read once
    fn callable(&mut self, kind: &'static KindSpec, name: String, own_name: &str, decl: Node<'_>, func: &Func, roles: &[String], scope: &FileScope<'_>, owner: Option<&Owner<'_>>) {
        if is_trivial(func) {
            return;
        }
        let method = owner.is_some();
        if !self.lenses.is_empty() {
            let scope_canon = scope_canonical(func, &self.file_names);
            let facts = crate::lenses::function_facts(func, method, roles, &self.file_names, scope_canon);
            self.push_lens(&name, decl, &facts);
        }
        // A method is dispatched through every class that inherits it, and a magic one by the runtime:
        // no call names it alone.
        let read = decides(func, scope, method || magic(own_name));
        let AnalyzedFn { cluster_canonical, xname_canonical, type3_lines, type_refs, type3_units, statements, size } =
            analyze(own_name, func);
        let identity = match owner {
            Some(o) => scope.method_identity(&o.decl.name, own_name),
            None => scope.identity(own_name),
        };
        let canon = DefCanon {
            cluster: Some(cluster_canonical),
            analysis: Some(Analysis { xname_canonical, type3_lines, type_refs, type3_units, size, canon_dialect: CanonDialect::Php }),
            facets: Facets {
                statements,
                reaches: reaches(func, scope.names, owner),
                decides: read.atoms,
                identity: Some(identity),
                params: read.params,
                calls: read.calls,
                mentions: read.mentions,
                loose_keywords: read.loose,
            },
        };
        self.push(kind, name, decl, func.params.len(), canon);
    }

    fn function(&mut self, decl: Node<'_>, names: &Names) {
        let Some(name) = field(decl, "name").map(|n| text(n, self.source).to_owned()) else { return };
        if !self.first(&FUNCTIONS, &name) {
            return;
        }
        let func = lower_func(decl, self.source);
        let roles = attribute_names(decl, self.source);
        let scope = FileScope { names, class: None, parent: None };
        self.callable(&FUNCTIONS, name.clone(), &name, decl, &func, &roles, &scope, None);
    }

    /// A class, trait, enum or interface: the declaration itself, then each of its methods.
    fn class(&mut self, decl: Node<'_>, names: &Names) {
        let Some(c) = lower_class(decl, self.source) else { return };
        let kind = if c.kind == "interface" { &INTERFACES } else { &CLASSES };
        // A declaration with no members is a name: an exception type (`class NotFound extends
        // \RuntimeException {}`), a marker interface. Two of one name are two names for a failure or a
        // capability, not a body written twice.
        if c.members.is_empty() || !self.first(kind, &c.name) {
            return;
        }
        if !self.lenses.is_empty() && c.kind != "interface" {
            let facts = crate::lenses::class_facts(&c, &self.file_names);
            self.push_lens(&c.name, decl, &facts);
        }
        let full = names.declared(&c.name);
        let parent = c.extends.first().map(|p| names.resolve(NameKind::Class, p).0);
        let scope = FileScope { names, class: Some(full), parent };
        let mut canon = DefCanon::body(Some(class_canon(&c)));
        if c.kind != "interface" {
            // A class is called with what its constructor takes.
            canon.facets.identity = Some(scope.identity(&c.name));
            let ctor = c.members.iter().find_map(|m| match m {
                ClassMember::Method { name, sig, .. } if name.eq_ignore_ascii_case("__construct") => Some(sig),
                _ => None,
            });
            if let Some(sig) = ctor.filter(|s| !s.params.iter().any(|p| p.variadic)) {
                canon.facets.params = sig.params.iter().map(|p| Arc::from(p.name.as_str())).collect();
            }
        }
        self.push(kind, c.name.clone(), decl, 0, canon);
        let owner = Owner::new(&c);
        let methods: Vec<Node<'_>> =
            field(decl, "body").map(kids).unwrap_or_default().into_iter().filter(|m| m.kind() == "method_declaration").collect();
        for m in methods {
            let Some(method) = field(m, "name").map(|n| text(n, self.source).to_owned()) else { continue };
            if field(m, "body").is_none() {
                continue; // abstract, or an interface's: no body to compare
            }
            let qualified = format!("{}::{method}", c.name);
            if !self.first(&METHODS, &qualified) {
                continue;
            }
            let func = lower_func(m, self.source);
            let mut roles = modifiers(m, self.source);
            roles.extend(attribute_names(m, self.source));
            self.callable(&METHODS, qualified, &method, m, &func, &roles, &scope, Some(&owner));
        }
    }

    /// `const A = 1, B = 2;` at file scope.
    fn consts(&mut self, decl: Node<'_>) {
        let elements: Vec<Node<'_>> = kids(decl).into_iter().filter(|k| k.kind() == "const_element").collect();
        let single = elements.len() == 1;
        for e in elements {
            let Some(name) = kids(e).into_iter().next().map(|n| text(n, self.source).to_owned()) else { continue };
            if self.first(&CONSTANTS, &name) {
                self.push(&CONSTANTS, name, if single { decl } else { e }, 0, DefCanon::body(None));
            }
        }
    }

    /// `define('NAME', value);` at file scope.
    fn define(&mut self, stmt: Node<'_>) {
        let Some(call) = kids(stmt).into_iter().next().filter(|c| c.kind() == "function_call_expression") else { return };
        let Expr::Call { f, args } = lower_expr(call, self.source) else { return };
        if !matches!(f.as_ref(), Expr::Name(n) if n.trim_start_matches('\\').eq_ignore_ascii_case("define")) {
            return;
        }
        let Some(Expr::Lit("Str", name)) = args.first().map(|a| &a.value) else { return };
        if args.len() < 2 || name.is_empty() || !self.first(&CONSTANTS, name) {
            return;
        }
        self.push(&CONSTANTS, name.clone(), stmt, 0, DefCanon::body(None));
    }
}

/// The dotted paths a callable reaches: every class, function and constant it names that its file
/// imported or wrote fully qualified — and, in a method, the class of every property it reads off
/// `$this`: a dependency a class is handed is reached through the property it is kept in.
fn reaches(f: &Func, names: &Names, owner: Option<&Owner<'_>>) -> Vec<Arc<str>> {
    let mut out: Vec<Arc<str>> = Vec::new();
    let mut add = |kind: NameKind, spelled: &str| {
        let (full, imported) = names.resolve(kind, spelled);
        if imported {
            out.push(Arc::from(dotted(&full)));
        }
    };
    for (kind, name) in free_names(f) {
        add(kind, &name);
    }
    if let Some(owner) = owner {
        for prop in this_props(&f.body) {
            if let Some(ty) = owner.props.get(&prop) {
                type_names(ty, &mut |class| add(NameKind::Class, class));
            }
        }
    }
    out.sort();
    out.dedup();
    out
}

/// The properties a body reads off `$this`.
fn this_props(body: &[Stmt]) -> HashSet<String> {
    fn expr(e: &Expr, out: &mut HashSet<String>) {
        if let Expr::Prop { e: recv, name: Member::Name(n), .. } = e {
            if matches!(recv.as_ref(), Expr::Var(v) if v == "this") {
                out.insert(n.clone());
            }
        }
        crate::canon::for_each_child(e, &mut |c| match c {
            crate::canon::Child::Expr(x) => expr(x, out),
            crate::canon::Child::Body(b) => stmts(b, out),
        });
    }
    fn stmts(list: &[Stmt], out: &mut HashSet<String>) {
        for s in list {
            crate::canon::each_stmt_part(s, &mut |p| match p {
                crate::canon::Part::Stmt(inner) => stmts(std::slice::from_ref(inner), out),
                crate::canon::Part::Stmts(l) => stmts(l, out),
                crate::canon::Part::Expr(e) => expr(e, out),
            });
        }
    }
    let mut out = HashSet::new();
    stmts(body, &mut out);
    out
}

/// Every name a file introduces — its functions, classes and their members, constants — what every lens
/// erases before it looks.
fn file_bound_names(items: &[Node<'_>], src: &str) -> HashSet<String> {
    let mut out = HashSet::new();
    for item in items {
        match item.kind() {
            "function_definition" => out.extend(field(*item, "name").map(|n| text(n, src).to_owned())),
            "class_declaration" | "trait_declaration" | "enum_declaration" | "interface_declaration" => {
                if let Some(c) = lower_class(*item, src) {
                    out.insert(c.name.clone());
                    for m in &c.members {
                        match m {
                            ClassMember::Const { name, .. } | ClassMember::Method { name, .. } | ClassMember::Case { name, .. } => {
                                out.insert(name.clone());
                            }
                            ClassMember::Prop { .. } | ClassMember::TraitUse(_) => {}
                        }
                    }
                }
            }
            "const_declaration" => {
                for e in kids(*item).into_iter().filter(|k| k.kind() == "const_element") {
                    out.extend(kids(e).into_iter().next().map(|n| text(n, src).to_owned()));
                }
            }
            _ => {}
        }
    }
    out
}

/// Scan one PHP source string → its definitions as [`Def`]s with canon precomputed. A declaration
/// holding a syntax error is still read: the grammar recovers inside it.
#[must_use]
pub fn scan_source(source: &str, file: &Arc<str>, opts: &ScanOpts) -> Vec<Def> {
    if is_generated(source) || !source.contains("<?") || is_not_code(file) {
        return Vec::new();
    }
    let Some(tree) = parse(source) else { return Vec::new() };
    let root = tree.root_node();
    let lines = LineMap::new(source);
    let namespaced = blocks(root, source);
    let lenses = enabled_lenses(opts);
    let file_names = if lenses.is_empty() {
        HashSet::new()
    } else {
        namespaced.iter().flat_map(|(_, items)| file_bound_names(&top_items(items), source)).collect()
    };
    let mut b = Builder { source, lines: &lines, file, lenses, file_names, seen: HashSet::new(), out: Vec::new() };
    for (names, items) in &namespaced {
        for item in top_items(items) {
            match item.kind() {
                "function_definition" => b.function(item, names),
                "class_declaration" | "trait_declaration" | "enum_declaration" | "interface_declaration" => b.class(item, names),
                "const_declaration" => b.consts(item),
                "expression_statement" => b.define(item),
                _ => {}
            }
        }
    }
    b.out
}

/// Every use site in one source — what [`collect_sites`] reads: its functions, its methods, and its
/// top-level code as one more body. A generated file holds no sites, as it holds no definitions.
pub(crate) fn file_sites(source: &str, path: &str, known: &HashSet<&str>) -> Vec<dup_defs_core::uses::Site> {
    if is_generated(source) || !source.contains("<?") || is_not_code(path) {
        return Vec::new();
    }
    let Some(tree) = parse(source) else { return Vec::new() };
    let mut funcs = Vec::new();
    let mut top: Vec<Stmt> = Vec::new();
    for (_, items) in blocks(tree.root_node(), source) {
        for item in top_items(&items) {
            match item.kind() {
                "function_definition" => funcs.push(lower_func(item, source)),
                "class_declaration" | "trait_declaration" | "enum_declaration" => {
                    if let Some(c) = lower_class(item, source) {
                        funcs.extend(c.members.into_iter().filter_map(|m| match m {
                            ClassMember::Method { func, .. } => func,
                            _ => None,
                        }));
                    }
                }
                "expression_statement" | "echo_statement" | "return_statement" | "foreach_statement" | "for_statement" | "while_statement"
                | "switch_statement" | "try_statement" => top.extend(lower_block_of(item, source)),
                _ => {}
            }
        }
    }
    if !top.is_empty() {
        funcs.push(Func { params: Vec::new(), ret: None, by_ref: false, body: top });
    }
    collect_sites(&funcs, known)
}

/// One top-level statement as a body of one statement.
fn lower_block_of(item: Node<'_>, src: &str) -> Vec<Stmt> {
    match crate::ir::lower_stmt(item, src) {
        Stmt::Block(b) => b,
        Stmt::Empty => Vec::new(),
        s => vec![s],
    }
}

