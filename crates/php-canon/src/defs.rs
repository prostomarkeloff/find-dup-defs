//! File-scope definition scan for PHP — the "find-*" step of `find-dup-defs`.
//!
//! Parses each file **once** with tree-sitter and lowers every tracked declaration straight to the
//! engine's [`Def`], computing its canonical strings off the syntax tree (no re-parse). Surfaces:
//!
//! * **functions** — every `function` declared at file scope, in a namespace block, or under a
//!   conditional (`if (!function_exists('f')) { function f() … }`, PHP's way of declaring a function
//!   only when nothing else has).
//! * **methods** — every method with a body of a class, trait or enum, named `Class::method`. `$this`
//!   is written `self`.
//! * **classes** — `class`, `trait` and `enum` declarations.
//! * **interfaces** — `interface` declarations.
//! * **constants** — a file-scope `const`, and a `define('NAME', value)` — the older spelling, and still
//!   the commoner one in WordPress-era code.
//!
//! PHP has no type aliases. A name declared twice in one file is declared once per configuration —
//! `if (PHP_VERSION_ID >= 80000) { function f() … } else { function f() … }` — and the first is
//! reported, as the C frontend reports a preprocessor's alternatives.
//!
//! A file that declares itself generated (`@generated`, `DO NOT EDIT` in the comments before its code,
//! see [`is_generated`]) yields nothing: its duplication is the generator's, and editing it is not how
//! it would be fixed. A file with no `<?php` in it is all template text and yields nothing either, which
//! is why the frontend may claim the extensions other tools share (`.inc`).

