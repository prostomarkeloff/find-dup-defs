/// The banners generators write at the top of what they write.
const GENERATED: &[&str] = &[
    "do not edit",
    "automatically generated",
    "autogenerated",
    "auto-generated",
    "a bison parser",
    "generated by flex",
    "generated by gperf",
    "generated by re2c",
    "generated by the protocol buffer compiler",
    "generated by swig",
];

/// Whether a file declares itself generated: a generator's banner in the comments before its first
/// line of code (a `#line` marker, which a generator writes first, is not code).
pub(crate) fn is_generated(src: &str) -> bool {
    let mut in_block = false;
    for line in src.lines().take(200) {
        let t = line.trim();
        let comment = in_block || t.starts_with("//") || t.starts_with("/*") || t.is_empty() || t.starts_with("#line");
        if !comment {
            return false;
        }
        if t.contains("/*") && !t.contains("*/") {
            in_block = true;
        } else if t.contains("*/") {
            in_block = false;
        }
        let lower = t.to_ascii_lowercase();
        if GENERATED.iter().any(|m| lower.contains(m)) {
            return true;
        }
    }
    false
}

/// What one run knows beyond the file being read: the attribute macros the corpus defines, the
/// headers it holds, and the directory every path is read relative to.
pub(crate) struct Corpus {
    pub(crate) macros: Macros,
    pub(crate) root: PathBuf,
    pub(crate) headers: Headers,
}

impl Corpus {
    /// A corpus of one file: the compiler's own attribute words, no headers, its directory the root.
    pub(crate) fn single(file: &str) -> Self {
        let root = Path::new(file).parent().map(Path::to_path_buf).unwrap_or_default();
        Self { macros: Macros::builtin(), root, headers: Headers::default() }
    }

    /// Everything a run's files say about each other: read once, before any of them is scanned.
    pub(crate) fn build(files: &[Arc<str>]) -> Self {
        let sources: Vec<Option<String>> = files.par_iter().map(|f| std::fs::read_to_string(&**f).ok()).collect();
        let macros = Macros::learn(sources.iter().flatten().map(String::as_str));
        let root = common_root(files);
        let headers = Headers::read(&root, files, &macros);
        Self { macros, root, headers }
    }
}

/// The deepest directory every file of the run is under.
fn common_root(files: &[Arc<str>]) -> PathBuf {
    let mut root: Option<PathBuf> = None;
    for f in files {
        let dir = Path::new(&**f).parent().map(Path::to_path_buf).unwrap_or_default();
        root = Some(match root {
            None => dir,
            Some(r) => r.components().zip(dir.components()).take_while(|(a, b)| a == b).map(|(a, _)| a).collect(),
        });
    }
    root.unwrap_or_default()
}

/// The declarations a file holds at file scope, wherever a conditional, a linkage block or a stretch
/// the parser could not read put them.
fn top_items(root: Node<'_>) -> Vec<Node<'_>> {
    fn walk<'t>(nodes: Vec<Node<'t>>, out: &mut Vec<Node<'t>>) {
        for n in nodes {
            match n.kind() {
                "preproc_if" | "preproc_ifdef" => {
                    for (_, held) in preproc_branches(n) {
                        walk(held, out);
                    }
                }
                "linkage_specification" => {
                    if let Some(body) = field(n, "body") {
                        if body.kind() == "declaration_list" {
                            walk(kids(body), out);
                        } else {
                            out.push(body);
                        }
                    }
                }
                "ERROR" => walk(kids(n), out),
                _ => out.push(n),
            }
        }
    }
    let mut out = Vec::new();
    walk(kids(root), &mut out);
    out
}

/// How many bytes of a body the parser could not read: the outermost `ERROR` nodes in it.
fn damage(body: Node<'_>) -> usize {
    let mut lost = 0;
    let mut stack = vec![body];
    while let Some(n) = stack.pop() {
        if n.is_error() {
            lost += n.end_byte() - n.start_byte();
            continue;
        }
        if n.has_error() {
            let mut cursor = n.walk();
            stack.extend(n.children(&mut cursor));
        }
    }
    lost
}

/// Whether a body is too broken to read: a quarter of it or more is parse error.
fn too_damaged(body: Node<'_>) -> bool {
    damage(body) * 4 > (body.end_byte() - body.start_byte()).max(1)
}

/// True when a body is a no-op or a stub: empty, a single `return` of a name or a literal, or a
/// single call that does not return — the shapes that are not refactor clusters. A `(void)x;` marking
/// a parameter unused is not a statement. A member read (`return s->len;`), a call, and anything
/// structural fall through and are compared.
fn is_trivial(f: &Func) -> bool {
    let unused = |s: &&Stmt| matches!(s, Stmt::Expr(Expr::Cast { ty: Type::Named(t), e }) if t == "void" && matches!(e.as_ref(), Expr::Name(_)));
    let body: Vec<&Stmt> = f.body.iter().filter(|s| !unused(s)).collect();
    match body.as_slice() {
        [] | [Stmt::Return(None)] => true,
        [Stmt::Return(Some(e))] => is_atom(e),
        [Stmt::Expr(Expr::Call { f, .. })] => {
            matches!(f.as_ref(), Expr::Name(n) if matches!(n.as_str(), "abort" | "exit" | "_exit" | "panic" | "BUG"))
        }
        _ => false,
    }
}

fn is_atom(e: &Expr) -> bool {
    match e {
        Expr::Name(_) | Expr::Lit(..) | Expr::Null | Expr::Bool(_) => true,
        Expr::Unary { op, e } if op == "-" => is_atom(e),
        Expr::Cast { e, .. } | Expr::Paren(e) => is_atom(e),
        _ => false,
    }
}

/// Whether a declaration is `static`.
fn is_static(decl: Node<'_>, src: &str) -> bool {
    kids(decl).into_iter().any(|k| k.kind() == "storage_class_specifier" && text(k, src) == "static")
}

/// Whether a declaration's base type is `const`-qualified.
fn is_const(decl: Node<'_>, src: &str) -> bool {
    kids(decl).into_iter().any(|k| k.kind() == "type_qualifier" && text(k, src) == "const")
}

/// A record whose members are all function pointers: a table of methods.
fn is_method_table(fields: &[FieldDecl]) -> bool {
    fields.len() >= 2
        && fields.iter().all(|f| match &f.ty {
            Type::Ptr(inner) => matches!(inner.as_ref(), Type::Func(..)),
            Type::Func(..) => true,
            _ => false,
        })
}

/// What a file defines, read before its definitions are: the names it declares `static`, the records
/// it writes out, and every name it introduces.
struct FileFacts {
    statics: HashSet<String>,
    records: Vec<(String, Vec<FieldDecl>)>,
    names: HashSet<String>,
}

fn file_facts(items: &[Node<'_>], src: &str) -> FileFacts {
    let mut facts = FileFacts { statics: HashSet::new(), records: Vec::new(), names: HashSet::new() };
    for &item in items {
        match item.kind() {
            "function_definition" => {
                if let Some(parts) = fn_parts(item, src) {
                    if parts.is_static {
                        facts.statics.insert(parts.name.clone());
                    }
                    facts.names.insert(parts.name);
                }
            }
            "declaration" | "type_definition" => {
                let spec = field(item, "type");
                if let Some(t) = spec {
                    if let Type::Record { name, fields, .. } = lower_spec(t, src) {
                        let mut named = name.into_iter().collect::<Vec<_>>();
                        if item.kind() == "type_definition" {
                            named.extend(fields_names(item, src));
                        }
                        for n in named {
                            facts.records.push((n.clone(), fields.clone()));
                            facts.names.insert(n);
                        }
                    } else if let Type::Enum { name, items } = lower_spec(t, src) {
                        facts.names.extend(name);
                        facts.names.extend(items.into_iter().map(|(n, _)| n));
                    }
                }
                let stat = is_static(item, src);
                for name in fields_names(item, src) {
                    if stat {
                        facts.statics.insert(name.clone());
                    }
                    facts.names.insert(name);
                }
            }
            "preproc_def" | "preproc_function_def" => {
                if let Some(name) = field(item, "name") {
                    facts.names.insert(text(name, src).to_owned());
                }
            }
            "struct_specifier" | "union_specifier" | "enum_specifier" => match lower_spec(item, src) {
                Type::Record { name: Some(name), fields, .. } => {
                    facts.records.push((name.clone(), fields));
                    facts.names.insert(name);
                }
                Type::Enum { name, items } => {
                    facts.names.extend(name);
                    facts.names.extend(items.into_iter().map(|(n, _)| n));
                }
                _ => {}
            },
            _ => {}
        }
    }
    facts
}

/// The names a declaration's declarators declare.
fn fields_names(decl: Node<'_>, src: &str) -> Vec<String> {
    fields(decl, "declarator").into_iter().filter_map(|d| declarate(Type::Other, d, src).0).collect()
}

/// What a definition contributes beyond its location: its canonical forms and, for a function, the
/// facets the perspective passes read.
struct DefCanon {
    cluster: Option<String>,
    analysis: Option<Analysis>,
    facets: Facets,
}

impl DefCanon {
    /// A body-bearing kind clustered by its canonical text alone (a record), or a raw-text kind
    /// (`None`).
    fn body(cluster: Option<String>) -> Self {
        Self { cluster, analysis: None, facets: Facets::default() }
    }
}

/// One builder so every push site stays uniform.
struct Builder<'a> {
    /// The file as written — what a definition's text is read from.
    source: &'a str,
    /// The file as parsed — what every node is read from (same offsets).
    src: &'a str,
    lines: &'a LineMap<'a>,
    file: &'a Arc<str>,
    corpus: &'a Corpus,
    /// The headers the file's includes reach, nearest first.
    closure: Vec<usize>,
    /// Which lenses this run asked for; empty when it did not ask.
    lenses: Vec<Lens>,
    /// Names the file itself introduced — what every lens erases before it looks.
    file_names: HashSet<String>,
    /// What the file's names stand for, as the decisions pass writes them.
    decides: FileScope,
    /// Whether any pass of this run reads the per-definition facets, so they are worth computing.
    facets: bool,
    /// The kinds and names already reported: a second definition of one is another configuration's.
    seen: HashSet<(&'static str, String)>,
    /// The macros the file defines as parameters of something else rather than as constants: the ones
    /// it `#undef`s again, and every one it defines before including a template.
    parameters: HashSet<String>,
    out: Vec<Def>,
}

impl Builder<'_> {
    /// Whether this is the file's first definition of `name` as `kind`.
    fn first(&mut self, kind: &'static KindSpec, name: &str) -> bool {
        self.seen.insert((kind.id, name.to_owned()))
    }

    /// One lens [`Def`] for this definition, when the run asked for lenses and the projection has
    /// enough to say. The record, the thinness floor and the scoring are the shared module's.
    fn push_lens(&mut self, name: &str, span: Node<'_>, facts: &LensFacts) {
        if self.lenses.is_empty() {
            return;
        }
        let start = span.start_byte();
        let (line, col) = self.lines.loc0(start);
        let loc = count_loc(self.source.get(start..span.end_byte()).unwrap_or(""));
        let site = DefSite { name, file: self.file, line, col, loc };
        if let Some(def) = lens_def("c", CanonDialect::C, &site, &self.lenses, facts) {
            self.out.push(def);
        }
    }

    fn push(&mut self, kind: &'static KindSpec, name: String, span: Node<'_>, args: usize, canon: DefCanon) {
        let DefCanon { cluster: cluster_canonical, analysis, facets } = canon;
        let (start, end) = (span.start_byte(), span.end_byte());
        let (line, col) = self.lines.loc0(start);
        let text_orig = self.source.get(start..end).unwrap_or("").trim_end().to_owned();
        let loc = count_loc(&text_orig);
        self.out.push(Def {
            lang: "c",
            kind,
            name,
            file: Arc::clone(self.file),
            line,
            col,
            loc,
            args,
            text_orig,
            cluster_canonical,
            analysis,
            thickness: None,
            facets,
        });
    }

    fn function(&mut self, def: Node<'_>) {
        let Some(parts) = fn_parts(def, self.src) else { return };
        if too_damaged(parts.body) {
            return;
        }
        let func = lower_func(&parts, self.src);
        if is_trivial(&func) || !self.first(&FUNCTIONS, &parts.name) {
            return;
        }
        if !self.lenses.is_empty() {
            let scope = scope_canonical(&func, &self.file_names);
            let locals = locals_of(&func);
            let roles: Vec<String> = parts
                .specifiers
                .iter()
                .filter(|s| matches!(s.as_str(), "static" | "inline" | "extern" | "_Noreturn" | "__inline" | "__inline__" | "__forceinline"))
                .cloned()
                .collect();
            let facts = crate::lenses::function_facts(&func, &roles, &locals, &self.file_names, scope);
            self.push_lens(&parts.name, def, &facts);
        }
        let read = if self.facets {
            decides(&func, &self.decides, parts.name == "main")
        } else {
            DecisionFacts::default()
        };
        let AnalyzedFn { cluster_canonical, xname_canonical, type3_lines, type_refs, type3_units, statements, size } =
            analyze(&parts.name, &func, self.facets);
        let reaches = if self.facets {
            let names = free_names(&func);
            self.corpus.headers.reaches(&self.closure, names.iter())
        } else {
            Vec::new()
        };
        let identity = self.facets.then(|| self.decides.identity(&parts.name));
        let canon = DefCanon {
            cluster: Some(cluster_canonical),
            analysis: Some(Analysis { xname_canonical, type3_lines, type_refs, type3_units, size, canon_dialect: CanonDialect::C }),
            facets: Facets {
                statements,
                reaches,
                decides: read.atoms,
                identity,
                params: read.params,
                calls: read.calls,
                mentions: read.mentions,
                loose_keywords: read.loose,
            },
        };
        let args = func.params.len();
        self.push(&FUNCTIONS, parts.name, def, args, canon);
    }

    /// A `struct` / `union` / `enum` written out at file scope, named by its tag — or, under a
    /// `typedef`, by the name the `typedef` gives it.
    fn record(&mut self, decl: Node<'_>, spec: Node<'_>, typedef: Option<String>) {
        match lower_spec(spec, self.src) {
            Type::Record { kind, name, fields } => {
                let Some(name) = typedef.or(name) else { return };
                let table = is_method_table(&fields);
                let kind_spec = if table { &INTERFACES } else { &CLASSES };
                if !self.first(kind_spec, &name) {
                    return;
                }
                if !self.lenses.is_empty() {
                    let facts = crate::lenses::record_facts(&fields, &self.file_names);
                    self.push_lens(&name, decl, &facts);
                }
                let mut canon = DefCanon::body(Some(record_canon(kind, &name, &fields)));
                if !table && self.facets {
                    // A record is constructed by its initializer, which sets its members.
                    canon.facets.identity = Some(self.decides.identity(&name));
                    if let Some(members) = self.decides.record(&name) {
                        canon.facets.params = members.iter().map(|(m, _)| Arc::from(m.as_str())).collect();
                    }
                }
                self.push(kind_spec, name, decl, 0, canon);
            }
            Type::Enum { name, items } => {
                let Some(name) = typedef.or(name) else { return };
                if self.first(&CLASSES, &name) {
                    let canon = DefCanon::body(Some(enum_canon(&name, &items)));
                    self.push(&CLASSES, name, decl, 0, canon);
                }
            }
            _ => {}
        }
    }

    /// A file-scope declaration: a record it writes out, and its `const` objects with a value.
    fn declaration(&mut self, decl: Node<'_>) {
        if let Some(spec) = field(decl, "type").filter(|t| field(*t, "body").is_some()) {
            self.record(decl, spec, None);
        }
        if !is_const(decl, self.src) {
            return;
        }
        let declarators = fields(decl, "declarator");
        let single = declarators.len() == 1;
        for d in declarators {
            if d.kind() != "init_declarator" {
                continue;
            }
            let (Some(name), ty) = declarate(Type::Other, d, self.src) else { continue };
            if matches!(ty, Type::Func(..)) || !self.first(&CONSTANTS, &name) {
                continue;
            }
            self.push(&CONSTANTS, name, if single { decl } else { d }, 0, DefCanon::body(None));
        }
    }

    /// A `typedef`: of a record written out, that record; of anything else, an alias per name.
    fn typedef(&mut self, decl: Node<'_>) {
        let names = fields_names(decl, self.src);
        if let Some(spec) = field(decl, "type").filter(|t| field(*t, "body").is_some()) {
            self.record(decl, spec, names.into_iter().next());
            return;
        }
        for name in names {
            if self.first(&TYPE_ALIASES, &name) {
                self.push(&TYPE_ALIASES, name, decl, 0, DefCanon::body(None));
            }
        }
    }

    /// An object-like `#define` with a value — a constant, unless it is one of the attribute macros
    /// erased before parsing.
    fn define(&mut self, def: Node<'_>) {
        let Some(name) = field(def, "name").map(|n| text(n, self.src).to_owned()) else { return };
        let has_value = field(def, "value").is_some_and(|v| !text(v, self.src).trim().is_empty());
        if !has_value || self.corpus.macros.erases(&name) || self.parameters.contains(&name) || !self.first(&CONSTANTS, &name) {
            return;
        }
        self.push(&CONSTANTS, name, def, 0, DefCanon::body(None));
    }
}

/// The macros a file defines as parameters rather than as constants.
///
/// A constant is defined to be used for as long as its file is. A macro the file takes back with
/// `#undef`, or one of the run of `#define`s written just before including a template
/// (`#define BIT_DEPTH 8` then `#include "dsp_template.c"`), is an argument passed by hand — and every
/// instantiation of the template passes its own, under the same name, so as constants they would be
/// the commonest "duplicate" of a C tree that instantiates templates.
fn parameter_macros(items: &[Node<'_>], src: &str) -> HashSet<String> {
    let mut out = HashSet::new();
    let mut defined: Vec<String> = Vec::new();
    for item in items {
        match item.kind() {
            "preproc_def" => {
                if let Some(name) = field(*item, "name") {
                    defined.push(text(name, src).to_owned());
                }
            }
            "preproc_call" => {
                let directive = field(*item, "directive").map_or("", |d| text(d, src));
                if directive == "#undef" {
                    if let Some(arg) = field(*item, "argument") {
                        out.insert(text(arg, src).trim().to_owned());
                    }
                }
            }
            "preproc_include" => {
                let path = field(*item, "path").map_or("", |p| text(p, src));
                let path = path.trim_matches(['"', '<', '>']);
                let source = Path::new(path).extension().is_some_and(|e| e.eq_ignore_ascii_case("c"));
                let template = source || path.contains("template") || path.contains("tmpl");
                if template {
                    out.extend(defined.drain(..));
                } else {
                    defined.clear();
                }
            }
            // Anything else ends the run of definitions a template include would take as arguments.
            _ => defined.clear(),
        }
    }
    out
}

/// Scan one C source string → its definitions as [`Def`]s with canon precomputed, as a run of this one
/// file would: no headers to resolve names through, the compiler's attribute words only.
#[must_use]
pub fn scan_source(source: &str, file: &Arc<str>, opts: &ScanOpts) -> Vec<Def> {
    scan_file(source, file, opts, &Corpus::single(file))
}

/// Scan one C source string within a run.
pub(crate) fn scan_file(source: &str, file: &Arc<str>, opts: &ScanOpts, corpus: &Corpus) -> Vec<Def> {
    if is_generated(source) {
        return Vec::new();
    }
    let prepared = prepare(source, &corpus.macros);
    let src: &str = &prepared;
    let Some(tree) = parse(src) else { return Vec::new() };
    let root = tree.root_node();
    let lines = LineMap::new(source);
    let items = top_items(root);
    let facts = file_facts(&items, src);
    let lenses = enabled_lenses(opts);
    let want_facets = opts.facets;
    // The headers the file's includes reach, for a definition's reaches — facets-only data, so a run
    // that reads no facets skips the walk that resolves them.
    let closure = if want_facets {
        corpus.headers.closure(Path::new(&**file), &Headers::includes_of(root, src))
    } else {
        Vec::new()
    };
    let module = dotted_under(&corpus.root, Path::new(&**file));
    let mut b = Builder {
        source,
        src,
        lines: &lines,
        file,
        corpus,
        closure,
        lenses,
        file_names: if opts.wants("lenses") { facts.names.clone() } else { HashSet::new() },
        decides: FileScope::new(module, facts.statics, &facts.records),
        facets: want_facets,
        seen: HashSet::new(),
        parameters: parameter_macros(&items, src),
        out: Vec::new(),
    };
    for item in items {
        match item.kind() {
            "function_definition" => b.function(item),
            "declaration" => b.declaration(item),
            "type_definition" => b.typedef(item),
            // `struct tag { … };` — a type written out and nothing declared with it.
            "struct_specifier" | "union_specifier" | "enum_specifier" if field(item, "body").is_some() => b.record(item, item, None),
            "preproc_def" => b.define(item),
            _ => {}
        }
    }
    b.out
}

/// Every use site in one source — what [`collect_sites`] reads, gathered off the file: its functions,
/// and the initializers of its file-scope objects. A generated file holds no sites, as it holds no
/// definitions.
pub(crate) fn file_sites(source: &str, known: &HashSet<&str>, corpus: &Corpus) -> Vec<dup_defs_core::uses::Site> {
    if is_generated(source) {
        return Vec::new();
    }
    let prepared = prepare(source, &corpus.macros);
    let src: &str = &prepared;
    let Some(tree) = parse(src) else { return Vec::new() };
    let mut items = FileItems { funcs: Vec::new(), initializers: Vec::new() };
    for item in top_items(tree.root_node()) {
        match item.kind() {
            "function_definition" => {
                if let Some(parts) = fn_parts(item, src).filter(|p| !too_damaged(p.body)) {
                    items.funcs.push(lower_func(&parts, src));
                }
            }
            "declaration" => {
                for d in fields(item, "declarator").into_iter().filter(|d| d.kind() == "init_declarator") {
                    if let Some(value) = field(d, "value") {
                        items.initializers.push(crate::ir::lower_expr(value, src));
                    }
                }
            }
            _ => {}
        }
    }
    collect_sites(&items, known)
}

