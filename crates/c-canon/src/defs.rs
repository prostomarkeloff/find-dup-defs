//! File-scope definition scan for C — the "find-*" step of `find-dup-defs`.
//!
//! Parses each file **once** with tree-sitter — after [`crate::prep`] has erased what only a
//! preprocessor could read — and lowers every tracked declaration straight to the engine's [`Def`],
//! computing its canonical strings off the syntax tree (no re-parse). Surfaces:
//!
//! * **functions** — every function definition, `static` or not. A `static` function's name is its
//!   file's, but a helper copied into ten files under one name is the duplication this tool looks for,
//!   so it is named as written; the decisions pass, which needs identities, qualifies it by its file.
//! * **classes** — a `struct`, `union` or `enum` written out with a body, named by its tag or by the
//!   `typedef` that names it.
//! * **interfaces** — a `struct` of function pointers and nothing else: C's interface, a table of
//!   methods (`struct file_operations`, `AVCodec`'s callbacks), the analog of Go's `interface` and
//!   Rust's `trait`.
//! * **constants** — an object-like `#define` with a value, and a file-scope `const` object with an
//!   initializer (a lookup table copied between files is the commonest C duplicate after a helper).
//! * **type-aliases** — every other `typedef`.
//!
//! What a preprocessor conditional holds is read whichever branch it is in — a definition under
//! `#ifdef` is a definition — and a name the file defines twice is defined once per configuration:
//! the first is reported ([`crate::build`]). A function whose body the parser could not read for the
//! most part is skipped; a body with a stray error in it — a macro the parser took for something else —
//! is read around it.
//!
//! A file that declares itself generated (`DO NOT EDIT`, a Bison or flex banner, see
//! [`is_generated`]) yields nothing: its duplication is the generator's, and editing it is not how it
//! would be fixed.

