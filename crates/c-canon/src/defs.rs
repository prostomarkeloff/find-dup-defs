    #[test]
    fn divergent_bodies_with_identical_handling_share_their_use_facts() {
        use dup_defs_core::uses::use_facts;
        // Two caches whose declarations share nothing, written by key, read by key and swept by age
        // the same way.
        let a = concat!(
            "struct image_cache { const char *key; unsigned char *blob; long dead_at; };\n",
            "void put_image(struct session *s, const char *k, unsigned char *v) { session_add(s, &(struct image_cache){ .key = k, .blob = v, .dead_at = soon() }); }\n",
            "struct row *get_image(struct session *s, const char *k) { return session_find(s, by_key(sizeof(struct image_cache), k)); }\n",
            "void reap_images(struct session *s) { session_delete(s, older_than(sizeof(struct image_cache), now())); }\n",
        );
        let b = concat!(
            "struct prompt_store { struct json *payload; int version; };\n",
            "void put_prompt(struct session *s, const char *k, struct json *v) { session_add(s, &(struct prompt_store){ .key = k, .blob = v, .dead_at = soon() }); }\n",
            "struct row *get_prompt(struct session *s, const char *k) { return session_find(s, by_key(sizeof(struct prompt_store), k)); }\n",
            "void reap_prompts(struct session *s) { session_delete(s, older_than(sizeof(struct prompt_store), now())); }\n",
        );
        let (fa, fb): (Arc<str>, Arc<str>) = (Arc::from("a.c"), Arc::from("b.c"));
        let opts = ScanOpts::default();
        let mut defs = scan_source(a, &fa, &opts);
        defs.extend(scan_source(b, &fb, &opts));
        let corpus = super::Corpus::single("a.c");
        let facts = use_facts(&[(a, "a.c", 1), (b, "b.c", 1)], &defs, |src, _path, known| super::file_sites(src, known, &corpus));
        let get = |n: &str| facts.get(n).unwrap_or_else(|| panic!("no use facts for {n}: {facts:?}")).clone();
        assert_eq!(get("image_cache"), get("prompt_store"), "identical handling ⇒ identical use facts");
    }

